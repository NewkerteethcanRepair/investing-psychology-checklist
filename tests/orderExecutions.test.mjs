import assert from 'node:assert/strict';
import { buildOrderExecutions, mergeOrderExecutions } from '../src/composables/orderExecutions.mjs';
import { analyzeTrades } from '../src/composables/journalAnalysis.mjs';
const row = (id, side, quantity, pnl = '0', symbol = 'BTC-USDT-SWAP') => ({ 'Order ID': id, 'Order Time': `2026-11-01 10:00:${id.padStart(2,'0')}`, Symbol: symbol, Side: side, 'Filled Amount': String(quantity), 'Amount Unit': 'cont', PNL: pnl, Fee: '-1', 'Fee Unit': 'USDT', 'Price Unit': 'USDT' });
const data = { orders: [row('1','Open long',2),row('2','Open long',1),row('3','Close long',1,'10'),row('4','Close long',2,'-3'),row('5','Open long',1),row('6','Close short',2,'5'),row('7','Open short',1),row('8','Close short',1,'2'),row('9','Open long',0)], unmatchedFills: [] };
const trades=buildOrderExecutions(data);
assert.equal(trades.length,4);
assert.equal(trades.filter(t=>t.status==='closed').length,2);
const complete=trades.find(t=>t.actions.length===4);
assert.equal(complete.psychology.result.netPnl,3);
assert.equal(complete.actions[2].type,'reduce');
assert.equal(complete.actions[3].type,'exit');
assert.equal(trades.find(t=>t.psychology.orderExecution.startMissing).status,'open');
assert.equal(analyzeTrades(trades).settled,2);
assert.equal(trades.reduce((n,t)=>n+t.actions.length,0),8);
assert.deepEqual(buildOrderExecutions({...data,orders:[...data.orders].reverse()}),trades);
complete.review='耐心执行';complete.psychology.quickDiscipline='followed';complete.psychology.result.discipline='followed';
const merged=mergeOrderExecutions(trades,buildOrderExecutions(data));
assert.equal(merged.length,4);assert.equal(merged.find(t=>t.id===complete.id).review,'耐心执行');
assert.equal(merged.find(t=>t.id===complete.id).psychology.result.discipline,'followed');
assert.match(complete.id,/^[\da-f]{8}-[\da-f]{4}-4[\da-f]{3}-8[\da-f]{3}-[\da-f]{12}$/);
const excess=buildOrderExecutions({orders:[row('1','Open long',1),row('2','Close long',2)]});
assert.equal(excess[0].psychology.orderExecution.complete,false);
console.log('Automatic trading groups: partial exits, multiple directions, boundaries, stable reimport, optional review preservation and accounting passed.');
